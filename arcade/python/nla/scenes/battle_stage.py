HURT = ((T.MOON, 2), (T.MOON, -2), (T.RED, 2), (T.RED, -1), (None, 1), (None, 0))
HURT_FAST = ((T.MOON, 2), (T.RED, -2))
HURT_BIG = ((T.MOON, 0), (T.RED, 0))
KO_RAMP = (T.SILVER1, T.SILVER1, T.NIGHT4, T.NIGHT4, T.NIGHT3, T.NIGHT3, T.NIGHT3)
SILHOUETTE = T.NIGHT3


class Actor:
    """One fighter on the stage. `facing` is +1 when the target is to the right (Domino) and -1 for rats."""

    def __init__(self, char, center_x, facing, stage):
        w, h = CHARS[char]["size"]
        self.sprite = SpriteObj(char, center_x - w // 2, FLOOR_FEET_Y + 1 - h)
        stage.add(self.sprite)
        self.stage = stage
        self.facing = facing
        self.t = 0.0                # idle clock
        self.seq = None             # (steps, index, time in step)
        self.seq_loop = False
        self.hurt = []              # remaining HURT steps (consumed per tick)
        self.ko_step = -1           # >= 0 while sinking / after
        self.hold_fid = None        # fixed pose (victory end)
        self.lunge = 0
        self.shake = (0, 0)         # extra stage shake offset (crit)
        self.hops = []
        self.then_hold = None
        self.frozen = None
        self.big = w * h > 5000     # 96x96 boss: moving it costs two 8k px repaints, so it only flashes and animates
        self.sprite.opaque = self.big and center_x > 240

    # -- poses
    @property
    def top_center(self):
        w, h = self.sprite.size
        bb = self.sprite.tab["bbox"]["i0"] or (0, 0, w, h)
        return (self.sprite.cx + w // 2, self.sprite.cy + bb[1])

    def mouth(self):
        w, h = self.sprite.size
        return (self.sprite.cx + int(w * 0.36), self.sprite.cy + int(h * 0.42))

    def center(self):
        w, h = self.sprite.size
        bb = self.sprite.tab["bbox"]["i0"] or (0, 0, w, h)
        return (self.sprite.cx + bb[0] + bb[2] // 2, self.sprite.cy + bb[1] + bb[3] // 2)

    def swap(self, char):
        sp = self.sprite
        sp.char = char
        sp.fid = "i0"
        self.frozen = None
        self.seq = None
        self.hold_fid = None
        w, h = sp.size
        sp.cx = sp.cx + 0
        sp.cy = FLOOR_FEET_Y + 1 - h

    def play(self, seq, loop=False, then_hold=None):
        steps = [s for s in seq if self.sprite.has(s[0])]
        if steps:
            self.seq, self.seq_loop = [steps, 0, 0.0], loop
            self.then_hold = then_hold if self.sprite.has(then_hold or "") else None

    def hop(self):
        self.hops = [-4, -8, -9, -6, -2, 0]

    def seq_busy(self):
        return self.seq is not None

    def start_hurt(self, fast=False):
        self.hurt = list(HURT_BIG if self.big else (HURT_FAST if fast else HURT))

    def start_ko(self):
        self.ko_step = 0
        self.seq = None
        self.hurt = []

    def hold(self, fid):
        self.hold_fid = fid if self.sprite.has(fid) else None

    # -- stepping
    def update(self, dt):
        """dt in (scaled) seconds: advances idle clock and animation sequences."""
        self.t += dt
        if self.seq is not None:
            steps, i, t = self.seq
            t += dt
            while t >= steps[i][2]:
                t -= steps[i][2]
                i += 1
                if i >= len(steps):
                    if self.seq_loop:
                        i = 0
                    else:
                        self.seq = None
                        if self.then_hold:
                            self.hold_fid, self.then_hold = self.then_hold, None
                        break
            if self.seq is not None:
                self.seq = [steps, i, t]

    def tick(self):
        """Once per scene tick: hurt and defeat steps, then write the sprite look."""
        sp = self.sprite
        tint, dx = None, 0
        if self.hurt:
            tint, dx = self.hurt.pop(0)
            dx = 0 if self.big else dx * -self.facing
        oy = 0
        if self.ko_step >= 0:
            s = self.ko_step
            tint = T.MOON if s == 0 else (KO_RAMP[s - 1] if s <= len(KO_RAMP) else SILHOUETTE)
            oy = 0 if self.big else min(8, s * 2)
            self.ko_step = min(s + 1, 99)
            fid = self.hold_fid or "i0"
        elif self.seq is not None:
            steps, i, _t = self.seq
            fid, lunge, _d = steps[i]
            dx += 0 if self.big else lunge * self.facing
        elif self.hold_fid:
            fid = self.hold_fid
        else:
            n = sp.idle_frames()
            fid = "i%d" % (int(self.t * (4 if n else 1)) % n) if n else "b0"
        if self.big and tint is not None:
            if self.frozen is None or not sp.has(self.frozen):
                self.frozen = sp.fid if sp.has(sp.fid) else "i0"
            fid = self.frozen
        else:
            self.frozen = None
        sp.fid = fid
        sp.ox = dx + self.shake[0]
        if self.hops:
            oy += self.hops.pop(0)
        sp.oy = oy + self.shake[1]
        sp.tint = tint
