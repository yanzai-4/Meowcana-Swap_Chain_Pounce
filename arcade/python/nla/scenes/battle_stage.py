"""Battle stage: a small dirty-rect compositor for the attic (backdrop + fighters + effects) and the fighter state
machine.

Everything that moves on the stage is an `Obj` with a z-order. Each frame `Stage.draw` collects the rectangles that
changed (old and new place of every object), repaints the backdrop under them with `asset_region` of `bg_attic`
(always exact) and then paints every object that touches the rectangle, in z order. A fighter that only changes
animation frame repaints just the pixels that differ (`battle_bounds.py`, generated by tools/gen_battle_bounds.py).
Work that does not fit the frame budget is carried over to the next frame (a big rectangle is cut into strips).

    stage = Stage()
    stage.add(obj) / obj.dead = True
    stage.update()                         once per scene tick: steps the objects
    stage.draw(scr, limit_ms)              dirty-rect repaint; returns after the budget is used up
    stage.build_step(scr, px)              progressive first paint of the backdrop (rows 30..231); `stage.built`
    stage.restore_rect(scr, rect)          immediate exact repaint of a rect (popups closing, tutorial arrow erased)

Actor wraps a SpriteObj with the idle loop, one-shot animations with a lunge, the hurt reaction (white, red, shake),
the defeat (sink + tint ramp) and the victory stretch.
"""

import engine

from nla.ui import theme as T

from .battle_bounds import CHARS

STAGE = (0, 0, T.SCREEN_W, 232)
# flat backdrop colors by row on the right half of the attic (wall, the 1 px floor edge, floor planks)
FLAT_BANDS = ((30, 196, T.NIGHT1), (196, 197, T.GOLD0), (197, 232, T.NIGHT0))
PLATE_H = 30
OP_MS = 1.5           # per draw op (costmodel.OP_MS)
SLOW_PX_MS = 1 / 180.0
RUN_MS = 0.06


def blit_ms(w, h):
    """Transparent blit (bg=None): half the pixels at the slow rate plus three runs per row."""
    return w * h * SLOW_PX_MS / 2 + h * 3 * RUN_MS + OP_MS


def region_ms(w, h):
    """asset_region / text with bg=None: all pixels slow, one run per row."""
    return w * h * SLOW_PX_MS + h * RUN_MS + OP_MS


def inter(a, b):
    x0, y0 = max(a[0], b[0]), max(a[1], b[1])
    x1, y1 = min(a[0] + a[2], b[0] + b[2]), min(a[1] + a[3], b[1] + b[3])
    if x1 <= x0 or y1 <= y0:
        return None
    return (x0, y0, x1 - x0, y1 - y0)


def union(a, b):
    x0, y0 = min(a[0], b[0]), min(a[1], b[1])
    x1, y1 = max(a[0] + a[2], b[0] + b[2]), max(a[1] + a[3], b[1] + b[3])
    return (x0, y0, x1 - x0, y1 - y0)


def contains(a, b):
    return a[0] <= b[0] and a[1] <= b[1] and a[0] + a[2] >= b[0] + b[2] and a[1] + a[3] >= b[1] + b[3]


def _merge(entries, restore):
    """Merge overlapping rects of (rect, restore) entries when the union adds at most 500 px of unchanged area."""
    rects = [e[0] for e in entries]
    again = True
    while again:
        again = False
        for i in range(len(rects)):
            for j in range(i + 1, len(rects)):
                a, b = rects[i], rects[j]
                if inter(a, b) or (a[0] <= b[0] + b[2] and b[0] <= a[0] + a[2] and a[1] <= b[1] + b[3]
                                   and b[1] <= a[1] + a[3]):
                    u = union(a, b)
                    if u[2] * u[3] <= a[2] * a[3] + b[2] * b[3] + 500:
                        rects[i] = u
                        del rects[j]
                        again = True
                        break
            if again:
                break
    return [(r, restore) for r in rects]


def paint_asset(scr, asset, frame, x, y, clip):
    """Transparent draw of an asset frame, cropped to `clip` (a plain blit when nothing crops it)."""
    if clip is None or contains(clip, (x, y, asset.w, asset.h)):
        scr.blit(asset, frame, x, y)
        return
    r = inter((x, y, asset.w, asset.h), clip)
    if r:
        scr.asset_region(asset, frame, r[0], r[1], r[0] - x, r[1] - y, r[2], r[3])


# --------------------------------------------------------------------------- objects
class Obj:
    """A stage object. Subclasses implement key() (what it looks like), rect() and paint(scr, clip)."""

    z = 5
    dead = False
    _last = None
    _lrect = None

    @property
    def clippable(self):
        return False

    def step(self):
        pass

    def key(self):
        raise NotImplementedError

    def rect(self):
        raise NotImplementedError

    def paint(self, scr, clip=None):
        raise NotImplementedError

    def cost(self, clip):
        """Estimated ms to paint this object (clipped to `clip` when it can be)."""
        r = self.rect()
        return blit_ms(r[2], r[3])

    def delta(self):
        """[(rect, restore)] to repaint because the object changed; restore=True repaints the backdrop first."""
        if self.dead:
            r, self._lrect, self._last = self._lrect, None, None
            return [(r, True)] if r else []
        k = self.key()
        if k == self._last:
            return []
        r = self.rect()
        old = self._lrect
        self._last, self._lrect = k, r
        if old is None:
            return [(r, False)]
        if inter(old, r):
            return [(union(old, r), True)]
        return [(old, True), (r, False)]


class SpriteObj(Obj):
    """A fighter. look = (char, frame id, dx, dy, tint); untinted frames are painted as cropped regions."""

    z = 1

    def __init__(self, char, x, y):
        self.char, self.cx, self.cy = char, x, y
        self.fid, self.ox, self.oy, self.tint = "i0", 0, 0, None
        self.opaque = False     # paint with the flat backdrop color behind the sprite (big boss: no restore pass)
        self.recover = 0        # ticks after a tint ended: the repaint to normal colors must not be cut into strips

    @property
    def clippable(self):
        return self.tint is None

    @property
    def tab(self):
        return CHARS[self.char]

    @property
    def size(self):
        return self.tab["size"]

    def idle_frames(self):
        return sum(1 for f in self.tab["bbox"] if f[0] == "i")

    def has(self, fid):
        return fid in self.tab["bbox"]

    def _asset(self):
        suffix = {"b": "", "i": "_idle", "a": "_attack", "c": "_cast", "v": "_victory"}[self.fid[0]]
        return T.asset(self.char + suffix), int(self.fid[1:])

    def step(self):
        if self.recover:
            self.recover -= 1

    def key(self):
        return (self.char, self.fid, self.ox, self.oy, self.tint)

    def _abs(self, fid, ox, oy):
        bb = self.tab["bbox"][fid] or (0, 0, 1, 1)
        return (self.cx + ox + bb[0], self.cy + oy + bb[1], bb[2], bb[3])

    def rect(self):
        return self._abs(self.fid, self.ox, self.oy)

    def cost(self, clip):
        if self.tint is not None:
            w, h = self.size
            return blit_ms(w, h)
        r = inter(self.rect(), clip)
        if not r:
            return 0
        if self.opaque:
            return r[2] * r[3] * SLOW_PX_MS + OP_MS * 2
        return region_ms(r[2], r[3])

    def delta(self):
        k = self.key()
        p = self._last
        if k == p:
            return []
        r = self.rect()
        old = self._lrect
        self._last, self._lrect = k, r
        if p is None:
            return [(r, False)]
        char0, fid0, ox0, oy0, tint0 = p
        if tint0 is not None and self.tint is None:
            self.recover = 4
        if char0 == self.char and (ox0, oy0) == (self.ox, self.oy):
            if fid0 == self.fid:
                return [(r, False)]                                 # recolor in place, same coverage
            if self.opaque and tint0 is None and self.tint is None:
                rr, pr = self.tab["pair"]["%s>%s" % (fid0, self.fid)]
                ax, ay = self.cx + self.ox, self.cy + self.oy
                box = [(ax + q[0], ay + q[1], q[2], q[3]) for q in (rr, pr) if q]
                if not box:
                    return []
                return [(union(box[0], box[-1]) if len(box) > 1 else box[0], False)]
            if self.opaque:
                return [(self.canvas(), False)]
            if tint0 is None and self.tint is None:
                rr, pr = self.tab["pair"]["%s>%s" % (fid0, self.fid)]
                ax, ay = self.cx + self.ox, self.cy + self.oy
                rr = (ax + rr[0], ay + rr[1], rr[2], rr[3]) if rr else None
                pr = (ax + pr[0], ay + pr[1], pr[2], pr[3]) if pr else None
                if rr and pr:
                    return [(union(rr, pr), True)]
                return [(rr, True)] if rr else ([(pr, False)] if pr else [])
        if self.opaque:
            return [(self.canvas(), False)]
        if inter(old, r):
            return [(union(old, r), True)]
        return [(old, True), (r, False)]

    def canvas(self):
        w, h = self.size
        return (self.cx + self.ox, self.cy + self.oy, w, h)

    def paint(self, scr, clip=None):
        a, f = self._asset()
        x0, y0 = self.cx + self.ox, self.cy + self.oy
        if self.tint is not None:
            scr.blit(a, f, x0, y0, tint=self.tint)
            return
        r = inter(self.rect(), STAGE)
        if r and clip:
            r = inter(r, clip)
        if not r:
            return
        if self.opaque:
            for y0b, y1b, color in FLAT_BANDS:
                y_a, y_b = max(r[1], y0b), min(r[1] + r[3], y1b)
                if y_b > y_a:
                    scr.asset_region(a, f, r[0], y_a, r[0] - x0, y_a - y0, r[2], y_b - y_a, bg=color)
            return
        scr.asset_region(a, f, r[0], r[1], r[0] - x0, r[1] - y0, r[2], r[3])


class TextObj(Obj):
    """Floating text: centered on x, rising `rise` px over `frames` ticks; optional flash colors and shadow."""

    z = 8

    def __init__(self, x, y, text, color, font=T.BODY, scale=1, rise=14, frames=14, shadow=T.NIGHT0, flash=None,
                 hold=0):
        self.x, self.y, self.text, self.color, self.font, self.scale = x, y, text, color, font, scale
        self.rise, self.frames, self.shadow, self.flash, self.hold = rise, frames, shadow, flash, hold
        self.age = 0
        self._wh = engine.measure(text, font, scale)

    def step(self):
        self.age += 1
        self.dead = self.age > self.frames + self.hold

    def _dy(self):
        return -(self.rise * min(self.age, self.frames)) // max(1, self.frames)

    def _color(self):
        if self.flash and self.age < 6:
            return self.flash[(self.age // 2) % len(self.flash)]
        return self.color

    def key(self):
        return (self._dy(), self._color())

    def rect(self):
        w, h = self._wh
        x = min(max(2, self.x - w // 2), T.SCREEN_W - w - 2)
        return (x - 1, self.y + self._dy() - 1, w + 2, h + (3 if self.shadow is not None else 2))

    def cost(self, clip):
        w, h = self._wh
        return region_ms(w, h) * (2 if self.shadow is not None else 1)

    def paint(self, scr, clip=None):
        w, h = self._wh
        x = min(max(2, self.x - w // 2), T.SCREEN_W - w - 2)
        y = self.y + self._dy()
        if self.shadow is not None:
            scr.text(x, y + 2, self.text, self.shadow, None, self.font, self.scale)
        scr.text(x, y, self.text, self._color(), None, self.font, self.scale)


class AnimObj(Obj):
    """A baked asset played once (slash, spark, heal, curl, particles, hiss, bite); hold = ticks per frame."""

    z = 6

    def __init__(self, name, frames, x, y, hold=1, loops=1, dx=0, dy=0, bg=None):
        self.asset = T.asset(name)
        self.frames, self.x, self.y, self.hold, self.loops = list(frames), x, y, hold, loops
        self.dx, self.dy = dx, dy
        self.age = 0

    def step(self):
        self.age += 1
        self.dead = self.age >= len(self.frames) * self.hold * self.loops
        self.x += self.dx
        self.y += self.dy

    def _frame(self):
        return self.frames[(self.age // self.hold) % len(self.frames)]

    def key(self):
        return (self._frame(), int(self.x), int(self.y))

    def rect(self):
        return (int(self.x), int(self.y), self.asset.w, self.asset.h)

    @property
    def clippable(self):
        return True

    def cost(self, clip):
        r = inter(self.rect(), clip) if clip else self.rect()
        return region_ms(r[2], r[3]) if r else 0

    def paint(self, scr, clip=None):
        paint_asset(scr, self.asset, self._frame(), int(self.x), int(self.y), clip)


class StillObj(Obj):
    """A baked asset frame shown for `frames` ticks (MEOW bubble, status marker); frame list can change over time."""

    z = 7

    def __init__(self, name, x, y, frames, schedule):
        self.asset = T.asset(name)
        self.x, self.y, self.frames, self.schedule = x, y, frames, schedule     # schedule: [(from_tick, frame)]
        self.age = 0

    def step(self):
        self.age += 1
        self.dead = self.age > self.frames

    def _frame(self):
        f = self.schedule[0][1]
        for t, fr in self.schedule:
            if self.age >= t:
                f = fr
        return f

    def key(self):
        return self._frame()

    def rect(self):
        return (self.x, self.y, self.asset.w, self.asset.h)

    @property
    def clippable(self):
        return True

    def cost(self, clip):
        r = inter(self.rect(), clip) if clip else self.rect()
        return region_ms(r[2], r[3]) if r else 0

    def paint(self, scr, clip=None):
        paint_asset(scr, self.asset, self._frame(), self.x, self.y, clip)


class SparkObj(Obj):
    """A 2x2 ember rising and dying (element particles from a played card)."""

    z = 6

    def __init__(self, x, y, vx, vy, color, life):
        self.x, self.y, self.vx, self.vy, self.color, self.life = x, y, vx, vy, color, life
        self.age = 0

    def step(self):
        self.age += 1
        self.x += self.vx
        self.y += self.vy
        self.vy += 0.5 if self.age > self.life // 2 else 0
        self.dead = self.age >= self.life

    def key(self):
        return (int(self.x), int(self.y))

    def rect(self):
        return (int(self.x), int(self.y), 2, 2)

    def cost(self, clip):
        return OP_MS

    def paint(self, scr, clip=None):
        scr.fill_rect(int(self.x), int(self.y), 2, 2, self.color)


class PawObj(Obj):
    """The Paw marker over the active card; slides toward its target x (<= 26 px per tick)."""

    z = 9
    W, H = 15, 11

    def __init__(self, x, y):
        self.x, self.y = x, y
        self.tx = x
        self.visible = False
        self._shown = False

    def key(self):
        return (self.x, self.y, self.visible)

    def rect(self):
        return (self.x, self.y, self.W, self.H)

    def step(self):
        if self.x != self.tx:
            d = self.tx - self.x
            self.x += max(-26, min(26, d))

    def delta(self):
        k = self.key()
        if k == self._last:
            return []
        out = []
        if self._lrect:
            out.append((self._lrect, True))
        r = self.rect()
        if self.visible:
            out.append((r, False))
        self._last, self._lrect = k, (r if self.visible else None)
        return out

    def cost(self, clip):
        return blit_ms(self.W, self.H)

    def paint(self, scr, clip=None):
        if self.visible:
            scr.blit(T.asset("ui_paw"), 0, self.x, self.y)


class FlyCard(Obj):
    """A miniature card (16x22: gold rim, field color, white pip) flying along an arc, e.g. into Chubbs's mouth."""

    z = 7
    W, H = 16, 22

    def __init__(self, field, x0, y0, x1, y1, ticks):
        self.field, self.x0, self.y0, self.x1, self.y1, self.ticks = field, x0, y0, x1, y1, ticks
        self.age = 0

    def step(self):
        self.age += 1
        self.dead = self.age > self.ticks

    def _pos(self):
        t = min(1.0, self.age / self.ticks)
        t = t * t * (3 - 2 * t)
        return (int(self.x0 + (self.x1 - self.x0) * t), int(self.y0 + (self.y1 - self.y0) * t - 30 * 4 * t * (1 - t)))

    def key(self):
        return self._pos()

    def rect(self):
        x, y = self._pos()
        return (x, y, self.W, self.H)

    def cost(self, clip):
        return 3 * OP_MS + (self.W * self.H * 2) * SLOW_PX_MS

    def paint(self, scr, clip=None):
        x, y = self._pos()
        scr.fill_rect(x, y, self.W, self.H, T.GOLD2)
        scr.fill_rect(x + 2, y + 2, self.W - 4, self.H - 4, self.field)
        scr.fill_rect(x + 6, y + 8, 4, 4, T.MOON)


# --------------------------------------------------------------------------- compositor
class Stage:
    MAX_ENTRY_MS = 36.0

    def __init__(self):
        self.bg = T.asset("bg_attic")
        self.objs = []
        self.pending = []
        self.later = []
        self.built = False
        self._row = PLATE_H

    # -- objects
    def add(self, obj, delay=0):
        """Put an object on stage now, or `delay` ticks from now (staggers effects over frames: cheaper frames)."""
        if delay > 0:
            self.later.append([delay, obj])
        else:
            self.objs.append(obj)
            self.objs.sort(key=lambda o: o.z)
        return obj

    def update(self):
        for o in self.objs:
            o.step()
        if self.later:
            for item in self.later:
                item[0] -= 1
            ready = [i[1] for i in self.later if i[0] <= 0]
            self.later = [i for i in self.later if i[0] > 0]
            for o in ready:
                self.add(o)

    def invalidate(self):
        """Forget what is painted: the next frames rebuild the backdrop and repaint every object."""
        self.built = False
        self._row = PLATE_H
        self.pending = []
        self.later = []
        for o in self.objs:
            o._last = None
            o._lrect = None

    # -- progressive backdrop
    def build_step(self, scr, px=8800):
        rows = max(4, px // T.SCREEN_W)
        y = self._row
        h = min(rows, STAGE[3] - y)
        scr.asset_region(self.bg, 0, 0, y, 0, y, T.SCREEN_W, h, bg=0)
        self._row += h
        if self._row >= STAGE[3]:
            self.built = True

    def _restore_bg(self, scr, r):
        r = inter(r, (0, PLATE_H, STAGE[2], STAGE[3] - PLATE_H))
        if r:
            scr.asset_region(self.bg, 0, r[0], r[1], r[0], r[1], r[2], r[3], bg=0)

    # -- dirty rect machinery
    def _est(self, r, restore):
        ms = 0.0
        if restore:
            rr = inter(r, (0, PLATE_H, STAGE[2], STAGE[3] - PLATE_H))
            if rr:
                ms += rr[2] * rr[3] * SLOW_PX_MS + OP_MS
        for o in self.objs:
            if inter(o.rect(), r):
                ms += o.cost(r)
        return ms

    def _paint_entry(self, scr, r, restore):
        """Restore the backdrop under r (if asked), then paint every object that touches r in z order. A whole
        (unclippable) object that was painted can cover higher objects outside r: those are repainted too."""
        if restore:
            self._restore_bg(scr, r)
        touched = [r]
        for o in self.objs:
            orect = o.rect()
            hit = [t for t in touched if inter(orect, t)]
            if not hit:
                continue
            if o.clippable:
                if any(contains(t, orect) for t in hit):
                    o.paint(scr, None)
                else:
                    for t in hit:
                        o.paint(scr, t)
            else:
                o.paint(scr, None)
                touched.append(orect)

    def _atomic(self, r):
        """True when splitting r into strips would repaint an expensive unclippable object once per strip."""
        total = 0.0
        for o in self.objs:
            if getattr(o, "recover", 0) and inter(o.rect(), r):
                return True
            if not o.clippable and inter(o.rect(), r):
                total += o.cost(r)
        return total > 12.0

    def draw(self, scr, limit_ms=62.0):
        if not self.built:
            return
        ents = self.pending
        self.pending = []
        for o in self.objs:
            ents += o.delta()
        self.objs = [o for o in self.objs if not o.dead]
        if not ents:
            return
        clean = []
        for r, restore in ents:
            r = inter(r, STAGE)
            if r:
                clean.append((r, restore))
        restores = _merge([e for e in clean if e[1]], True)
        restores = [e for i, e in enumerate(restores)
                    if not any(contains(o[0], e[0]) and (o[0] != e[0] or j < i) for j, o in enumerate(restores)
                               if j != i)]
        paints = [p for p in _merge([e for e in clean if not e[1]], False)
                  if not any(contains(r[0], p[0]) for r in restores)]
        work = restores + paints
        first = True
        while work:
            r, restore = work.pop(0)
            est = self._est(r, restore)
            have = limit_ms - scr.stats()["ms"]
            if est > have and not (first and scr.stats()["ops"] == 0):
                self.pending.append((r, restore))
                self.pending.extend(work)
                return
            allow = min(self.MAX_ENTRY_MS, max(have, 12.0))
            if est > allow and r[3] > 6 and not self._atomic(r):
                rows = max(4, int(r[3] * allow / est))
                if rows < r[3]:
                    work.insert(0, ((r[0], r[1] + rows, r[2], r[3] - rows), restore))
                    r = (r[0], r[1], r[2], rows)
            self._paint_entry(scr, r, restore)
            first = False

    def queue_restore(self, rect):
        """Repaint the backdrop (and what stands on it) under `rect` over the next frames, strip by strip."""
        r = inter(rect, STAGE)
        if r:
            self.pending.append((r, True))

    def restore_rect(self, scr, rect):
        """Immediate exact repaint of a rect of the stage (popup closed, arrow erased, dialogue closed)."""
        r = inter(rect, STAGE)
        if not r or not self.built:
            return
        self._paint_entry(scr, r, True)


