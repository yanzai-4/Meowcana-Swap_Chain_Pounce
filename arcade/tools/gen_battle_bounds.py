"""Generate python/nla/scenes/battle_bounds.py: opaque bounding boxes of every fighter frame and, for every ordered
pair of frames of one fighter, the two rectangles the Battle stage needs to go from frame A to frame B in place:

    restore  bounding box of the pixels that are opaque in A but not in B (repaint the backdrop there first)
    paint    bounding box of the pixels of B that must be drawn afterwards (changed pixels + B inside `restore`)

Rects are (x, y, w, h) in canvas pixels, None when empty. Frame ids: b = base, i = idle, a = attack, c = cast,
v = victory plus the frame index ("i2"). Run from arcade/ after tools/pack_assets.py:

    python tools/gen_battle_bounds.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "python"))

import sim  # noqa: E402

OUT = ROOT / "python" / "nla" / "scenes" / "battle_bounds.py"
ANIMS = (("b", ""), ("i", "_idle"), ("a", "_attack"), ("c", "_cast"), ("v", "_victory"))


def bbox(mask, w, h):
    xs = [i % w for i, v in enumerate(mask) if v]
    ys = [i // w for i, v in enumerate(mask) if v]
    if not xs:
        return None
    return (min(xs), min(ys), max(xs) - min(xs) + 1, max(ys) - min(ys) + 1)


def main():
    lib = sim.Library()
    by_name = {a["name"]: (i, a) for i, a in enumerate(lib.assets)}
    keys = sorted(n[:-5] for n in by_name if n.endswith("_idle"))
    lines = ['"""GENERATED by tools/gen_battle_bounds.py. Do not edit.', '',
             'CHARS[name] = {"size": (w, h), "bbox": {frame id: rect}, "pair": {"A>B": (restore, paint)}};',
             'see the generator for the meaning of the rects."""', '', 'CHARS = {']
    for key in keys:
        frames = {}
        pix = {}
        size = None
        for letter, suffix in ANIMS:
            hit = by_name.get(key + suffix)
            if not hit:
                continue
            idx, a = hit
            size = (a["w"], a["h"])
            for f in range(a["frames"]):
                raw = lib.indices(idx, f)
                pix["%s%d" % (letter, f)] = raw
                frames["%s%d" % (letter, f)] = [1 if p else 0 for p in raw]
        w, h = size
        lines.append("    %r: {" % key)
        lines.append("        \"size\": %r," % (size,))
        lines.append("        \"bbox\": {%s}," % ", ".join("%r: %r" % (f, bbox(m, w, h)) for f, m in frames.items()))
        pairs = []
        for fa, ma in frames.items():
            for fb, mb in frames.items():
                if fa == fb:
                    continue
                pa, pb = pix[fa], pix[fb]
                lost = [1 if (ma[i] and not mb[i]) else 0 for i in range(w * h)]
                rr = bbox(lost, w, h)
                need = [1 if (mb[i] and (pa[i] != pb[i] or (rr and rr[0] <= i % w < rr[0] + rr[2]
                                                         and rr[1] <= i // w < rr[1] + rr[3]))) else 0
                        for i in range(w * h)]
                pairs.append("%r: (%r, %r)" % ("%s>%s" % (fa, fb), rr, bbox(need, w, h)))
        lines.append("        \"pair\": {%s}," % ", ".join(pairs))
        lines.append("    },")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT, len(keys), "fighters")


if __name__ == "__main__":
    main()
