"""Regenerate every non-character asset: assets/raw/ui/*.png, assets/ui.json, the UI section of docs/assets.md and
build/art_ui_sheet.png.   Usage:  python arcade/tools/art/build_ui.py   then   python arcade/tools/pack_assets.py

Each generator module exposes GENERATORS = {asset name: callable() -> list of RGBA frames}.  Names in spec.SPECS
without a generator get a sized placeholder (so a half-finished build still packs)."""
import importlib
import json
import os
import shutil
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from PIL import Image, ImageDraw

import pal
import spec
from pal import P

ROOT = HERE.parents[1]
RAW = ROOT / "assets" / "raw"
OUT = RAW / "ui"
MANIFEST = ROOT / "assets" / "ui.json"
DOC = ROOT / "docs" / "assets.md"
SHEET = ROOT / "build" / "art_ui_sheet.png"
MARK_BEGIN, MARK_END = "<!-- ui:begin -->", "<!-- ui:end -->"
MODULES = ["gen_icons", "gen_cards", "gen_fx", "gen_scenes"]


def collect():
    gens = {}
    for m in MODULES:
        if (HERE / (m + ".py")).exists():
            gens.update(importlib.import_module(m).GENERATORS)
    return gens


def placeholder(s, group_hue):
    frames = []
    for i in range(s.frames):
        im = Image.new("RGBA", (s.w, s.h), P[group_hue] + (255,))
        d = ImageDraw.Draw(im)
        d.rectangle([0, 0, s.w - 1, s.h - 1], outline=P["gold3"])
        d.line([0, 0, s.w - 1, s.h - 1], fill=P["gold1"])
        d.line([0, s.h - 1, s.w - 1, 0], fill=P["gold1"])
        frames.append(im)
    return frames


def validate(s, frames):
    assert len(frames) == s.frames, f"{s.name}: {len(frames)} frames, expected {s.frames}"
    for i, f in enumerate(frames):
        assert f.size == (s.w, s.h), f"{s.name}[{i}]: size {f.size}, expected {(s.w, s.h)}"
        assert f.mode == "RGBA", f"{s.name}[{i}]: mode {f.mode}"
        data = f.tobytes()
        for k in range(0, len(data), 4):
            r, g, b, a = data[k:k + 4]
            if a not in (0, 255):
                raise AssertionError(f"{s.name}[{i}]: partial alpha")
            if a and not pal.is565((r, g, b)):
                raise AssertionError(f"{s.name}[{i}]: color {(r, g, b)} not RGB565-exact")


def write_doc():
    lines = [MARK_BEGIN, "", "## Non-character art (generated by `tools/art/build_ui.py`, do not edit by hand)", "",
             "All assets are RGBA PNGs in `assets/raw/ui/`, listed in `assets/ui.json`. Alpha is 0 or 255 only "
             "(0 = transparent, index 0 in the packed palette). Every opaque color is an exact RGB565 value from the "
             "Moonlit Grimoire palette. Frame sets are multi-frame assets; `fps` 0 means a still or index-selected set.",
             ""]
    for g in spec.GROUPS:
        lines += [f"### {g}", "", "| name | size | frames | fps | meaning | frame index |", "|---|---|---|---|---|---|"]
        for s in spec.SPECS:
            if s.group == g:
                lines.append(f"| `{s.name}` | {s.w}x{s.h} | {s.frames} | {s.fps} | {s.meaning} | {s.index} |")
        lines.append("")
    lines += ["### Usage notes", ""] + spec.NOTES + ["", "### Coordinates for composed screens", ""]
    try:
        gs = importlib.import_module("gen_scenes")
        lines += gs.DOC_LINES
    except (ImportError, AttributeError):
        lines += ["(coordinates are added once scene art is final)"]
    lines += ["", MARK_END, ""]
    block = "\n".join(lines)
    if DOC.exists():
        text = DOC.read_text(encoding="utf-8")
        if MARK_BEGIN in text and MARK_END in text:
            pre = text.split(MARK_BEGIN)[0]
            post = text.split(MARK_END, 1)[1]
            text = pre + block + post.lstrip("\n")
        else:
            text = text.rstrip("\n") + "\n\n" + block
    else:
        text = "# Asset listing\n\nName, size, frames, fps, meaning and frame-index formula for every asset.\n\n" + block
    DOC.write_text(text, encoding="utf-8")


def contact_sheet(rendered):
    """Every asset on a night1 sheet (frame sets wrap), backdrops last at 1/2 scale."""
    small = [(s, f) for s, f in rendered if s.w * s.h <= 4000]
    big = [(s, f) for s, f in rendered if s.w * s.h > 4000]
    W = 960
    im = Image.new("RGB", (W, 2600), P["night1"])
    x = y = 6
    rowh = 0
    for s, frames in small:
        for f in frames:
            sc = 2 if s.w <= 16 else 1
            fw, fh = f.width * sc, f.height * sc
            if x + fw + 6 > W:
                x, y, rowh = 6, y + rowh + 6, 0
            tile = f.resize((fw, fh), Image.NEAREST) if sc != 1 else f
            im.paste(tile, (x, y), tile)
            x += fw + 4
            rowh = max(rowh, fh)
        x += 8
    y += rowh + 10
    x = 6
    rowh = 0
    for s, frames in big:
        if s.frames > 12:
            frames = frames[:12] + frames[16::4][:4]
        for f in frames:
            if x + f.width + 6 > W:
                x, y, rowh = 6, y + rowh + 6, 0
            im.paste(f, (x, y), f)
            x += f.width + 6
            rowh = max(rowh, f.height)
    y += rowh + 6
    im = im.crop((0, 0, W, y))
    SHEET.parent.mkdir(exist_ok=True)
    im.save(SHEET)


def main():
    gens = collect()
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    hues = {"Card faces": "night3", "Icons and glyphs": "gold1", "VFX sprites": "amber0", "Backdrops": "night2"}
    manifest, rendered, missing = [], [], []
    for s in spec.SPECS:
        if s.name in gens:
            frames = gens[s.name]()
        else:
            frames = placeholder(s, hues[s.group])
            missing.append(s.name)
        validate(s, frames)
        files = []
        for i, f in enumerate(frames):
            fn = f"{s.name}_{i:02d}.png"
            f.save(OUT / fn)
            files.append(f"ui/{fn}")
        manifest.append({"name": s.name, "size": [s.w, s.h], "fps": s.fps, "frames": files})
        rendered.append((s, frames))
    MANIFEST.write_text(json.dumps({"assets": manifest}, indent=1) + "\n", encoding="utf-8")
    write_doc()
    contact_sheet(rendered)
    colors = set()
    for _, frames in rendered:
        for f in frames:
            colors.update(c[1][:3] for c in f.getcolors(maxcolors=1 << 20) if c[1][3])
    print(f"{len(spec.SPECS)} assets, {sum(s.frames for s in spec.SPECS)} frames, {len(colors)} colors")
    if missing:
        print("placeholders:", ", ".join(missing))


if __name__ == "__main__":
    main()
